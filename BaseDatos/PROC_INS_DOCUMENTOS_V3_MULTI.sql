CREATE OR ALTER PROCEDURE [GLOBAL].[PROC_INS_DOCUMENTOS_V3_MULTI]
(
	@CLIENTE          VARCHAR(20),
	@DOCUMENTO        VARCHAR(100),
	@TIPO             VARCHAR(3),
	@SUBTIPO          INT,
	@CUENTA_BANCARIA  VARCHAR(50),
	@FECHA            VARCHAR(20),
	@REFERENCIA       VARCHAR(50),
	@MONEDA           VARCHAR(3),
	@TOTAL_ABONADO    DECIMAL(28,8),
	@CONCEPTO         VARCHAR(MAX),
	@IMG_COMPROBANTE1 VARCHAR(MAX),
	@IMG_COMPROBANTE2 VARCHAR(MAX),
	@ID_VISITA        INT,
	@VENDEDOR         VARCHAR(4),
	@COBRADOR         VARCHAR(4),
	@USUARIO          VARCHAR(100),
	@COMENTARIOCOB    VARCHAR(250),
	@CIA              VARCHAR(20),
	@DETALLE_APLICACION_JSON NVARCHAR(MAX) = NULL
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE
        @SQL NVARCHAR(MAX),
        @USUARIOEXISTE INT,
        @NUM_DOC_CB DECIMAL(28,0),
        @TIPO_CAMBIO DECIMAL(28,8),
        @MONEDA_CLIENTE VARCHAR(4) = NULL,
        @U_PS_ESTADO_LIQUIDACION INT;

    SET @USUARIOEXISTE = (SELECT COUNT(USUARIO) FROM EXACTUSERP.ERPADMIN.USUARIO WHERE USUARIO = @USUARIO);
    IF @USUARIOEXISTE <> 1 SET @USUARIO = 'sa';

    SET @NUM_DOC_CB = TRY_CONVERT(DECIMAL(28,0), @REFERENCIA);
    SET @U_PS_ESTADO_LIQUIDACION = TRY_CONVERT(INT, LTRIM(RTRIM(@REFERENCIA)));

    IF EXISTS (SELECT 1 FROM DIS86.DOCUMENTOS WHERE TIPO_DOC IN ('TEF','DEP') AND NUM_DOC_CB = @REFERENCIA)
        SET @REFERENCIA = CONCAT(@REFERENCIA, FORMAT(GETDATE(), 'ddMMyyyy'));

    SET @SQL = N'SELECT @TC = [GLOBAL].[GETTIPOCAMBIOFECHA](''USD'', CONVERT(DATETIME, @F + '' 23:59:59'', 120))';
    EXEC sp_executesql @SQL, N'@F VARCHAR(10), @TC DECIMAL OUTPUT', @F=@FECHA, @TC=@TIPO_CAMBIO OUTPUT;

    SET @SQL = N'UPDATE PS_TRACKING.'+QUOTENAME(@CIA)+N'.VISITAS SET DOCUMENTO=@D WHERE ID_VISITA=@V';
    EXEC sp_executesql @SQL, N'@D VARCHAR(50), @V INT', @D=@DOCUMENTO, @V=@ID_VISITA;

    DECLARE @LAST VARCHAR(15);
    SET @LAST = (
        SELECT @COBRADOR + RIGHT('000000000' + CAST(CAST(RIGHT(CO.ULTIMO_VALOR,9) AS INT)+1 AS VARCHAR(9)),9)
        FROM EXACTUSERP.DIS86.CONSECUTIVO CO
        WHERE CO.CONSECUTIVO = @COBRADOR
    );
    UPDATE EXACTUSERP.DIS86.CONSECUTIVO
      SET ULTIMO_VALOR = @LAST
    WHERE CONSECUTIVO = @COBRADOR;

    IF (@DETALLE_APLICACION_JSON IS NOT NULL AND LTRIM(RTRIM(@DETALLE_APLICACION_JSON)) <> '')
    BEGIN
        IF OBJECT_ID('tempdb..#DET') IS NOT NULL DROP TABLE #DET;
        SELECT
            CLIENTE,
            TIPO_DOC,
            DOCUMENTO,
            MONTO_APLICADO = CAST(MONTO_APLICADO AS DECIMAL(28,8))
        INTO #DET
        FROM OPENJSON(@DETALLE_APLICACION_JSON)
        WITH (
            CLIENTE        VARCHAR(20)   '$.CLIENTE',
            TIPO_DOC       VARCHAR(3)    '$.TIPO_DOC',
            DOCUMENTO      VARCHAR(50)   '$.DOCUMENTO',
            MONTO_APLICADO DECIMAL(28,8) '$.MONTO_APLICADO'
        );

        -- Enriquecer clientes por línea desde DOCUMENTOS_CC (si no vienen en JSON)
        UPDATE D
           SET D.CLIENTE = CC.CLIENTE
        FROM #DET D
        JOIN EXACTUSERP.DIS86.DOCUMENTOS_CC CC
          ON CC.DOCUMENTO = D.DOCUMENTO
         AND CC.TIPO      = D.TIPO_DOC
        WHERE ISNULL(LTRIM(RTRIM(D.CLIENTE)), '') = '';

        IF OBJECT_ID('tempdb..#CLI_AFECTADOS') IS NOT NULL DROP TABLE #CLI_AFECTADOS;
        SELECT DISTINCT CLIENTE
        INTO #CLI_AFECTADOS
        FROM #DET
        WHERE ISNULL(LTRIM(RTRIM(CLIENTE)), '') <> '';

        IF (@CLIENTE IS NOT NULL AND LTRIM(RTRIM(@CLIENTE)) <> '' AND @CLIENTE <> '0')
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM #CLI_AFECTADOS WHERE CLIENTE = @CLIENTE)
                INSERT INTO #CLI_AFECTADOS(CLIENTE) VALUES (@CLIENTE);
        END

        DECLARE @APLICA_TOTAL DECIMAL(28,8) = (SELECT ISNULL(SUM(MONTO_APLICADO),0) FROM #DET);
        IF (@APLICA_TOTAL > @TOTAL_ABONADO)
        BEGIN
            DECLARE @msg NVARCHAR(400);
            SET @msg = N'Suma de aplicaciones (' 
                     + CONVERT(NVARCHAR(50), CAST(@APLICA_TOTAL  AS DECIMAL(38,2))) 
                     + N') no puede exceder el total abonado (' 
                     + CONVERT(NVARCHAR(50), CAST(@TOTAL_ABONADO AS DECIMAL(38,2))) 
                     + N').';
            THROW 51001, @msg, 1;
        END

        -- Moneda del cliente cabecera (para el documento de depósito)
        IF (@CLIENTE IS NOT NULL AND @CLIENTE <> '' AND @CLIENTE <> '0')
        BEGIN
            SET @SQL = N'SELECT @OUT = MONEDA FROM EXACTUSERP.'+QUOTENAME(@CIA)+N'.CLIENTE WHERE CLIENTE=@C;';
            EXEC sp_executesql @SQL, N'@C VARCHAR(20), @OUT VARCHAR(4) OUTPUT', @C=@CLIENTE, @OUT=@MONEDA_CLIENTE OUTPUT;
        END

        SET @SQL = N'
;WITH J AS (
    SELECT
        CC.DOCUMENTO, CC.TIPO, CC.MONEDA,
        CC.SALDO, CC.SALDO_LOCAL, CC.SALDO_DOLAR, CC.SALDO_CLIENTE,
        DET.MONTO_APLICADO,
        CLI.MONEDA AS MONEDA_CLIENTE,
        CASE WHEN CC.MONEDA = ''CRC''
             THEN CASE WHEN @MONEDA_MOV = ''CRC'' THEN DET.MONTO_APLICADO ELSE DET.MONTO_APLICADO * @TC END
             ELSE CASE WHEN @MONEDA_MOV = ''USD'' THEN DET.MONTO_APLICADO ELSE DET.MONTO_APLICADO / @TC END
        END AS AP_DOC,
        CASE WHEN @MONEDA_MOV = ''CRC'' THEN DET.MONTO_APLICADO ELSE DET.MONTO_APLICADO * @TC END AS AP_LOCAL,
        CASE WHEN @MONEDA_MOV = ''USD'' THEN DET.MONTO_APLICADO ELSE DET.MONTO_APLICADO / @TC END AS AP_DOLAR,
        CASE WHEN CLI.MONEDA = @MONEDA_MOV THEN DET.MONTO_APLICADO
             WHEN CLI.MONEDA = ''CRC''      THEN DET.MONTO_APLICADO * @TC
             ELSE                                DET.MONTO_APLICADO / @TC END AS AP_CLIENTE
    FROM EXACTUSERP.'+QUOTENAME(@CIA)+'.DOCUMENTOS_CC CC
    JOIN #DET DET
      ON DET.DOCUMENTO = CC.DOCUMENTO
     AND DET.TIPO_DOC  = CC.TIPO
    JOIN EXACTUSERP.'+QUOTENAME(@CIA)+'.CLIENTE CLI
      ON CLI.CLIENTE = CC.CLIENTE
)
UPDATE CC
   SET
       CC.SALDO          = CASE WHEN J.AP_DOC     >= CC.SALDO         THEN 0 ELSE CC.SALDO         - J.AP_DOC     END,
       CC.SALDO_LOCAL    = CASE WHEN J.AP_LOCAL   >= CC.SALDO_LOCAL   THEN 0 ELSE CC.SALDO_LOCAL   - J.AP_LOCAL   END,
       CC.SALDO_DOLAR    = CASE WHEN J.AP_DOLAR   >= CC.SALDO_DOLAR   THEN 0 ELSE CC.SALDO_DOLAR   - J.AP_DOLAR   END,
       CC.SALDO_CLIENTE  = CASE WHEN J.AP_CLIENTE >= CC.SALDO_CLIENTE THEN 0 ELSE CC.SALDO_CLIENTE - J.AP_CLIENTE END,
       CC.FECHA_ULT_MOD  = GETDATE(),
       CC.USUARIO_ULT_MOD= @USUARIO,
       CC.U_PS_ESTADO_LIQUIDACION=@U_PS_ESTADO_LIQUIDACION
FROM EXACTUSERP.'+QUOTENAME(@CIA)+'.DOCUMENTOS_CC CC
JOIN J ON J.DOCUMENTO = CC.DOCUMENTO AND J.TIPO = CC.TIPO;';

        EXEC sp_executesql
            @SQL,
            N'@MONEDA_MOV VARCHAR(4), @TC DECIMAL, @USUARIO VARCHAR(100), @U_PS_ESTADO_LIQUIDACION INT',
            @MONEDA_MOV=@MONEDA, @TC=@TIPO_CAMBIO, @USUARIO=@USUARIO, @U_PS_ESTADO_LIQUIDACION=@U_PS_ESTADO_LIQUIDACION;

        -- Ajustar SALDO del documento crédito/deposito por total aplicado (sin depender de cliente)
        DECLARE
            @AP_LOCAL_TOTAL  DECIMAL(28,8) = CASE WHEN @MONEDA='CRC' THEN @APLICA_TOTAL ELSE @APLICA_TOTAL * @TIPO_CAMBIO END,
            @AP_DOLAR_TOTAL  DECIMAL(28,8) = CASE WHEN @MONEDA='USD' THEN @APLICA_TOTAL ELSE @APLICA_TOTAL / @TIPO_CAMBIO END,
            @AP_CLIENTE_TOT  DECIMAL(28,8) = @APLICA_TOTAL;

        SET @SQL = N'
UPDATE CC
   SET CC.SALDO          = CASE WHEN @APLICA_TOTAL  >= CC.SALDO         THEN 0 ELSE CC.SALDO         - @APLICA_TOTAL  END,
       CC.SALDO_LOCAL    = CASE WHEN @AP_LOCAL_TOTAL>= CC.SALDO_LOCAL   THEN 0 ELSE CC.SALDO_LOCAL   - @AP_LOCAL_TOTAL END,
       CC.SALDO_DOLAR    = CASE WHEN @AP_DOLAR_TOTAL>= CC.SALDO_DOLAR   THEN 0 ELSE CC.SALDO_DOLAR   - @AP_DOLAR_TOTAL END,
       CC.SALDO_CLIENTE  = CASE WHEN @AP_CLIENTE_TOT>= CC.SALDO_CLIENTE THEN 0 ELSE CC.SALDO_CLIENTE - @AP_CLIENTE_TOT END,
       CC.FECHA_ULT_MOD  = GETDATE(),
       CC.USUARIO_ULT_MOD= @USUARIO
FROM EXACTUSERP.'+QUOTENAME(@CIA)+'.DOCUMENTOS_CC CC
WHERE CC.TIPO = @TIPO
  AND CC.DOCUMENTO = @DOCUMENTO;';

        EXEC sp_executesql
            @SQL,
            N'@TIPO VARCHAR(3), @DOCUMENTO VARCHAR(100),
              @APLICA_TOTAL DECIMAL, @AP_LOCAL_TOTAL DECIMAL,
              @AP_DOLAR_TOTAL DECIMAL, @AP_CLIENTE_TOT DECIMAL,
              @USUARIO VARCHAR(100)',
            @TIPO=@TIPO, @DOCUMENTO=@DOCUMENTO,
            @APLICA_TOTAL=@APLICA_TOTAL, @AP_LOCAL_TOTAL=@AP_LOCAL_TOTAL,
            @AP_DOLAR_TOTAL=@AP_DOLAR_TOTAL, @AP_CLIENTE_TOT=@AP_CLIENTE_TOT,
            @USUARIO=@USUARIO;

        -- Recalcular saldos de todos los clientes impactados
        UPDATE C
           SET C.SALDO = ISNULL((
                        SELECT (ISNULL(SUM(CC.SALDO),0) - ISNULL((SELECT SUM(SALDO)
                                FROM EXACTUSERP.DIS86.DOCUMENTOS_CC (NOLOCK)
                                WHERE CC.CLIENTE = CLIENTE AND TIPO IN ('REC','O/C','DEP','TEF','N/C')), 0))
                        FROM EXACTUSERP.DIS86.DOCUMENTOS_CC CC (NOLOCK)
                        WHERE CC.CLIENTE = C.CLIENTE AND CC.TIPO NOT IN ('REC','O/C','DEP','TEF','N/C')
                        GROUP BY CC.CLIENTE),0),
               C.SALDO_DOLAR = ISNULL((
                        SELECT (ISNULL(SUM(CC.SALDO_DOLAR),0) - ISNULL((SELECT SUM(SALDO_DOLAR)
                                FROM EXACTUSERP.DIS86.DOCUMENTOS_CC (NOLOCK)
                                WHERE CC.CLIENTE = CLIENTE AND TIPO IN ('REC','O/C','DEP','TEF','N/C')), 0))
                        FROM EXACTUSERP.DIS86.DOCUMENTOS_CC CC (NOLOCK)
                        WHERE CC.CLIENTE = C.CLIENTE AND CC.TIPO NOT IN ('REC','O/C','DEP','TEF','N/C')
                        GROUP BY CC.CLIENTE),0),
               C.SALDO_LOCAL = ISNULL((
                        SELECT (ISNULL(SUM(CC.SALDO_LOCAL),0) - ISNULL((SELECT SUM(SALDO_LOCAL)
                                FROM EXACTUSERP.DIS86.DOCUMENTOS_CC (NOLOCK)
                                WHERE CC.CLIENTE = CLIENTE AND TIPO IN ('REC','O/C','DEP','TEF','N/C')), 0))
                        FROM EXACTUSERP.DIS86.DOCUMENTOS_CC CC (NOLOCK)
                        WHERE CC.CLIENTE = C.CLIENTE AND CC.TIPO NOT IN ('REC','O/C','DEP','TEF','N/C')
                        GROUP BY CC.CLIENTE),0)
        FROM EXACTUSERP.DIS86.CLIENTE C (NOLOCK)
        WHERE EXISTS (SELECT 1 FROM #CLI_AFECTADOS X WHERE X.CLIENTE = C.CLIENTE);
    END
END
GO
