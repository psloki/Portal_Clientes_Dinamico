function AplicarFiltros() {
    var arrayTemp = articulos
    var busquedastxt = $("#articulos").val()
    var busquedas = []

    try {
        busquedas = JSON.parse(busquedastxt);
    } catch (error) {
        busquedas = []
        console.error('Error al analizar el JSON:', error.message);
    }
    var clasificacion1 = $("#clas1").val()
    var clasificacion2 = $("#clas2").val()
    if (clasificacion1 != "0") {
        //Buscar clasificacion1
        arrayTemp = arrayTemp.filter((elemento) => elemento.CLASIFICACION1 === clasificacion1);
    }
    if (clasificacion2 != "0") {
        //Buscar clasificacion2
        arrayTemp = arrayTemp.filter((elemento) => elemento.CLASIFICACION2 === clasificacion2);
    }
    if (busquedas.length != 0) {
        arrayTemp = arrayTemp.filter((elemento) =>
            busquedas.some((palabra) => elemento.DESCRIPCIÓN.toLowerCase().includes(palabra.value.toLowerCase()) || elemento.CODIGO.toLowerCase().includes(palabra.value.toLowerCase()))
        );
    } else {
        arrayTemp = []
    }
    $('#miTabla tbody').remove()
    articulosFiltrados = arrayTemp
    KTDatatablesServerSide.reset()

}

