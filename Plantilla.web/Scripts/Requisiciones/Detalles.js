function agregarLinea() {
    let articulo = articulos.find(element => element.ARTICULO == $('#codigoarticulo').val());
    let objeto = {
        "ARTICULO": articulo.ARTICULO,
        "ARTICULO_NOMBRE": articulo.ARTICULO_NOMBRE,
        "BODEGA": $('#bodegconsumoa').val(),
        "EXISTENCIA": $('#existencia').val(),
        "CANTIDAD": $('#cantcons').val(),
        "CENTRO_COSTO": $('#centrocosto').val(),
        "CUENTA_CONTABLE": $('#cuentacontable').val()
    }
    lineas.push(objeto)
    KTDatatablesServerSide.reload()

    toastr.success('Se ha agregado el artículo con éxito', 'Éxito', toastrOptions)

    $("#codigoarticulo").val("").trigger("change")
    $("#articuloconsumo").val("").trigger("change")
    $("#bodegconsumoa").val("").trigger("change")
    $("#existencia").val("0").trigger("change")
    $("#cantcons").val("1").trigger("change")

}

function eliminarLinea(articulo) {
    let indexToRemove = lineas.findIndex(arti => arti.ARTICULO === articulo);
    if (indexToRemove !== -1) {
        lineas.splice(indexToRemove, 1);

        KTDatatablesServerSide.reload()

        toastr.success('Se ha eliminado la línea con éxito', 'Éxito', toastrOptions)
    }
}


