function spliter(text) {
    text = text.replaceAll(' ', '').replaceAll('\n', '').replaceAll('\r', '')
    let result
    let temp = ''
    for (let i = 0; i < text.length; i++) {
        temp += text.charAt(i)
        if ((i + 1) % 24 == 0) {
            temp += ','
        }
    }
    result = temp
    return result
}
function processData(array) {
    array = array.sort()
    const specimens = array.filter((number, i) => i == 0 ? true : array[i - 1] != number);

    const counterSpecimens = specimens.map(spec => {
        return { tag: spec, count: 0 };
    });

    counterSpecimens.map((countSpec, i) => {
        const actualSpecLength = array.filter(number => number === countSpec.tag).length;
        countSpec.count = actualSpecLength;
    })

    return counterSpecimens
}
