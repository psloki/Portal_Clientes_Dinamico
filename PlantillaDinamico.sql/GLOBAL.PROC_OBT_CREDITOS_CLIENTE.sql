ALTER  PROCEDURE [GLOBAL].[PROC_OBT_CREDITOS_CLIENTE]
(
@VENDEDOR VARCHAR(50),
@COBRADOR VARCHAR(10),
@CLIENTE VARCHAR(100),
@CIA VARCHAR(20)
)
AS
BEGIN
DECLARE @SQL NVARCHAR(MAX),@PARAM NVARCHAR(MAX)
DECLARE @TABLE TABLE(
                     TIPO VARCHAR(10), DOCUMENTO VARCHAR(100),SALDO DECIMAL(28,4),MONTO DECIMAL(28,4),APLICACION VARCHAR(MAX), FACTURA VARCHAR(100),
					 BOLETA VARCHAR(100),COMENTARIO VARCHAR(MAX),CLIENTE VARCHAR(100),VENDEDOR VARCHAR(100),FECHA_DOCUMENTO VARCHAR(100),COBRADOR VARCHAR(10)
					 )

SET @SQL = '
			SELECT   [TIPO]
					,[DOCUMENTO]
					,[SALDO]
					,[MONTO]
					,[APLICACION]
					,[FACTURA]
					,[BOLETA]
					,[COMENTARIO]
					,[CLIENTE]
					,[VENDEDOR]
					,[FECHA_DOCUMENTO]
					,[COBRADOR]
			  FROM 
			         '+ISNULL(@CIA,'')+'.[VIEW_OBT_DOCUMENTOS_CC_CREDITOS]
			  WHERE (CLIENTE   = @CLIENTE OR @CLIENTE = ''0'')
			 AND    (VENDEDOR  = @VENDEDOR  OR @VENDEDOR = ''0'') 
			 AND    (COBRADOR  = @COBRADOR  OR @COBRADOR = ''0'' OR COBRADOR IS NULL) 
			 '

	SET @PARAM ='@VENDEDOR VARCHAR(50),@COBRADOR VARCHAR(10),@CLIENTE VARCHAR(100)'

INSERT INTO @TABLE EXEC SP_EXECUTESQL @SQL,@PARAM,@VENDEDOR,@COBRADOR,@CLIENTE

SELECT  *  FROM @TABLE

END

