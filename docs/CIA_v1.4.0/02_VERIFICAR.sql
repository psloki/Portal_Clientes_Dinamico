SELECT @CIA AS CIA,o.Nombre,o.Tipo,
       CASE WHEN OBJECT_ID(QUOTENAME(@CIA)+N'.'+QUOTENAME(o.Nombre)) IS NULL THEN N'FALTA' ELSE N'EXISTE' END AS Estado
FROM @Objetos o ORDER BY o.Tipo,o.Nombre;
SELECT SCHEMA_NAME(o.schema_id) AS Esquema,o.name AS SP,p.name AS Parametro,t.name AS Tipo,p.max_length
FROM sys.objects o JOIN sys.parameters p ON p.object_id=o.object_id
JOIN sys.types t ON t.user_type_id=p.user_type_id
WHERE o.schema_id=SCHEMA_ID(N'DIS86') AND o.name IN (
N'PROC_EDI_DESCUENTO_CLIENTE_ARTICULO_MASIVO',N'PROC_EDI_BONIFICACION_CLIENTE_ARTICULO_MASIVO',N'PROC_OBT_CATALOGO_CIA',N'PROC_OBT_COMPROBANTE_PAGO_CIA') ORDER BY o.name,p.parameter_id;
DECLARE @Nombre SYSNAME,@Sql NVARCHAR(MAX);
DECLARE @Problemas TABLE (Objeto SYSNAME,Detalle NVARCHAR(4000));
DECLARE vistas CURSOR LOCAL FAST_FORWARD FOR SELECT Nombre FROM @Objetos WHERE Tipo='VIEW';
OPEN vistas; FETCH NEXT FROM vistas INTO @Nombre;
WHILE @@FETCH_STATUS=0
BEGIN
    BEGIN TRY
        SET @Sql=N'DECLARE @Conteo INT; SELECT @Conteo=COUNT(*) FROM (SELECT TOP (0) * FROM '+QUOTENAME(@CIA)+N'.'+QUOTENAME(@Nombre)+N') AS V;';
        EXEC sys.sp_executesql @Sql;
    END TRY
    BEGIN CATCH
        INSERT @Problemas VALUES(@Nombre,ERROR_MESSAGE());
    END CATCH;
    FETCH NEXT FROM vistas INTO @Nombre;
END;
CLOSE vistas; DEALLOCATE vistas;
SELECT * FROM @Problemas;
SELECT COUNT(*) AS DependenciasConError FROM @Problemas;
