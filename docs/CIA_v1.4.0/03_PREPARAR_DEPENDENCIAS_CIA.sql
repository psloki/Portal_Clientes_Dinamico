DECLARE @Nombre SYSNAME, @Tipo VARCHAR(10), @Sql NVARCHAR(MAX);
BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE objetos CURSOR LOCAL FAST_FORWARD FOR SELECT Nombre,Tipo,Definicion FROM @Objetos ORDER BY Orden;
    OPEN objetos;
    FETCH NEXT FROM objetos INTO @Nombre,@Tipo,@Sql;
    WHILE @@FETCH_STATUS=0
    BEGIN
        IF OBJECT_ID(QUOTENAME(@CIA)+N'.'+QUOTENAME(@Nombre)) IS NULL
            EXEC sys.sp_executesql @Sql;
        IF @Tipo='VIEW'
        BEGIN
            SET @Sql=N'SELECT TOP (0) * FROM '+QUOTENAME(@CIA)+N'.'+QUOTENAME(@Nombre)+N';';
            EXEC sys.sp_executesql @Sql;
        END;
        FETCH NEXT FROM objetos INTO @Nombre,@Tipo,@Sql;
    END;
    CLOSE objetos;
    DEALLOCATE objetos;
    COMMIT TRANSACTION;
    SELECT N'COMPLETADO' AS Estado,@CIA AS CIA;
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
    SELECT @CIA AS CIA,@Nombre AS ObjetoConError,ERROR_MESSAGE() AS Detalle;
    THROW;
END CATCH;
