		CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'') THEN SDOC.DESCRIPCION ELSE NULL END					  AS SUBTIPO_CREDITO,
		CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'') THEN DOC.MONTO ELSE 0 END 								  AS monto_credito,
		CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'') THEN DOC.SALDO ELSE 0 END 								  AS saldo_credito,
		CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'') THEN DOC.MONEDA ELSE NULL END							  AS MONEDA_CREDITO,
		CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'') THEN CONVERT(DATE,DOC.FECHA_DOCUMENTO)  ELSE NULL END    AS fecha_documento_credito,
