		,CASE  WHEN  DOC.TIPO NOT IN(''REC'',''TEF'',''O/C'',''DEP'') THEN CONVERT(DATE,DOC.CreateDate)   END             AS FECHA_CREACION_DEBITO
		,CASE  WHEN  DOC.TIPO IN(''REC'',''TEF'',''O/C'',''DEP'')     THEN CONVERT(DATE,DOC.CreateDate)   END             AS FECHA_CREACION_CREDITO
