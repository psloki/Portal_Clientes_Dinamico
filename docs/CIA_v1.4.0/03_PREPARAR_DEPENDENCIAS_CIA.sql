returns INT
as
begin 
	DECLARE @EXISTE INT = 0, @CONTADOR INT = 0, @VALOR VARCHAR(1)

	DECLARE @TABLE AS TABLE (VALOR VARCHAR(12))
	INSERT INTO @TABLE SELECT VAL FROM [__CIA__].[TF_SPLIT](@CONJUNTO,'','')

	DECLARE CONJUNTO CURSOR FOR 
	SELECT VALOR 
	FROM @TABLE 
	
	OPEN CONJUNTO  
	FETCH NEXT FROM CONJUNTO INTO @VALOR
	WHILE @@FETCH_STATUS = 0  
	BEGIN  
		  
		  IF(SELECT COUNT(*) WHERE @SUBCONJUNTO LIKE ''%''+@VALOR+''%'' )=1
		  BEGIN
			  SET @CONTADOR = @CONTADOR+1
		  END 

		  FETCH NEXT FROM CONJUNTO INTO @VALOR 
	END 
	
	CLOSE CONJUNTO
	DEALLOCATE CONJUNTO
	SELECT @EXISTE= IIF(COUNT(VAL)=@CONTADOR,1,0) FROM [__CIA__].TF_SPLIT(@SUBCONJUNTO,'','')
	RETURN @EXISTE

end');
