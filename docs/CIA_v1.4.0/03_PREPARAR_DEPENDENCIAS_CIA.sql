INSERT @Objetos VALUES (3,N'TF_SPLIT','FUNCTION',N'CREATE OR ALTER FUNCTION [__CIA__].[TF_SPLIT]
(
    @CADENA VARCHAR(MAX),
    @DELIMITER VARCHAR(1)
)
RETURNS @TABLE TABLE ( VAL VARCHAR(MAX) )
AS
BEGIN
    if @CADENA is null return
    declare @iStart int,
            @iPos int
    if substring( @CADENA, 1, 1 ) = @DELIMITER 
    begin
        set @iStart = 2
        insert into @TABLE
        values( null )
    end
    else 
        set @iStart = 1
    while 1=1
    begin
        set @iPos = charindex( @DELIMITER, @CADENA, @iStart )
        if @iPos = 0
            set @iPos = len( @CADENA )+1
        if @iPos - @iStart > 0          
            insert into @TABLE
            values  ( substring( @CADENA, @iStart, @iPos-@iStart ))
        else
            insert into @TABLE
            values( null )
        set @iStart = @iPos+1
        if @iStart > len( @CADENA ) 
            break
    end
    RETURN

END');
