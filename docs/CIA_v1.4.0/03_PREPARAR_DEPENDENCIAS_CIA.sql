		,CASE WHEN DATEDIFF(DAY,DOC.FECHA_VENCE,GETDATE())  > 0  AND DOC.SALDO > 0 THEN 1 ELSE 0 END              AS DOC_VENC
		,CASE  WHEN  DOC.TIPO NOT IN(''REC'',''TEF'',''O/C'',''DEP'') THEN DOC.APLICACION ELSE ISNULL(FAC.RUBRO5,'''') END  AS REFERENCIA_DEBITO
