CREATE OR ALTER PROCEDURE [GLOBAL].[PROC_INS_VISITA]( 
 @CLIENTE VARCHAR(20)
,@TIPO_VISITA VARCHAR(4)
,@FECHA_VISITA DATETIME
,@LATITUD VARCHAR(50)
,@LONGITUD VARCHAR(50)
,@ESTADO_VISITA VARCHAR(4)
,@COMENTARIO VARCHAR(800)
,@DOCUMENTO VARCHAR(50)
,@VENDEDOR VARCHAR(4)
,@USUARIO VARCHAR(50)
,@DOC_VENC_DESCRIPCION VARCHAR(800)
,@DIRECCION VARCHAR(MAX)
,@CIA VARCHAR(20)
,@ID_VISITA VARCHAR(20) OUT 
)
AS
BEGIN
    IF NULLIF(LTRIM(RTRIM(@CIA)), '') IS NULL
        THROW 50001, 'El parametro @CIA es obligatorio.', 1;

    DECLARE @SQL_CIA_BATCH NVARCHAR(MAX);
    SET @SQL_CIA_BATCH = CAST(N'' AS NVARCHAR(MAX)) + N'

	DECLARE @SQL NVARCHAR(MAX),@PARAM NVARCHAR(MAX),@LAST INT
	DECLARE @RUTA VARCHAR(4),@SEMANA VARCHAR(50),@DIA VARCHAR(10)

	 SET @RUTA   = (SELECT RUTA             FROM EXACTUSERP.' + QUOTENAME(@CIA) + N'.CLIENTE WHERE CLIENTE =@CLIENTE )
     SET @SEMANA = (SELECT U_SEMANA_VISITA  FROM EXACTUSERP.' + QUOTENAME(@CIA) + N'.CLIENTE WHERE CLIENTE =@CLIENTE )
	 SET @DIA    = (SELECT U_DIA_VISITA     FROM EXACTUSERP.' + QUOTENAME(@CIA) + N'.CLIENTE WHERE CLIENTE =@CLIENTE )
	
	
	---- SI EL CLIENTE NO TIENE DIA ASINGADO
	IF (@DIA = ''ND'' OR @DIA IS NULL OR @DIA = '''')
	BEGIN
		-- Obtener el día de la semana (1 = Domingo, 2 = Lunes, ..., 7 = Sábado)
		DECLARE @DiaDeLaSemana INT = DATEPART(WEEKDAY, @FECHA_VISITA);
    
		-- Asignar la letra del día correspondiente
		SET @DIA = CASE 
					WHEN @DiaDeLaSemana = 1 THEN ''D''  -- Domingo
					WHEN @DiaDeLaSemana = 2 THEN ''L''  -- Lunes
					WHEN @DiaDeLaSemana = 3 THEN ''K''  -- Martes
					WHEN @DiaDeLaSemana = 4 THEN ''M''  -- Miércoles
					WHEN @DiaDeLaSemana = 5 THEN ''J''  -- Jueves
					WHEN @DiaDeLaSemana = 6 THEN ''V''  -- Viernes
					WHEN @DiaDeLaSemana = 7 THEN ''S''  -- Sábado
				   END
	    END

		
		IF (@SEMANA IS NULL OR @SEMANA ='''' OR @SEMANA = ''ND'')
		BEGIN
		 SET @SEMANA = (SELECT semana 
		                FROM   ' + QUOTENAME(@CIA) + N'.VIW_OBT_SEMANA_POR_FECHA_VISITA
                        WHERE  CONVERT(VARCHAR(10), (@FECHA_VISITA), 105) BETWEEN inicio_semana AND fin_semana)

		END 

	 --SET @FECHA_VISITA = CONVERT(date, @FECHA_VISITA, 103)
      
	  
	   INSERT INTO ' + QUOTENAME(@CIA) + N'.[VISITAS]
					   (
						CLIENTE
					   ,TIPO_VISITA
					   ,FECHA_VISITA
					   ,LATITUD
					   ,LONGITUD
					   ,RUTA
					   ,SEMANA
					   ,DIA
					   ,ESTADO_VISITA
					   ,COMENTARIO
					   ,DOCUMENTO
					   ,VENDEDOR
					   ,USUARIO
                       ,DOC_VENC_DESCRIPCION
					   ,DIRECCION
						)
				 VALUES
					   (
					   	@CLIENTE
					   ,@TIPO_VISITA
					   ,@FECHA_VISITA --CONVERT(varchar,@FECHA_VISITA, 120)  
					   ,@LATITUD
					   ,@LONGITUD
					   ,@RUTA
					   ,@SEMANA
					   ,@DIA
					   ,@ESTADO_VISITA
					   ,@COMENTARIO
					   ,@DOCUMENTO
					   ,@VENDEDOR
					   ,@USUARIO	
					   ,@DOC_VENC_DESCRIPCION
					   ,@DIRECCION
					   )


	
	
	SET @LAST  = (SELECT MAX(ID_VISITA) FROM ' + QUOTENAME(@CIA) + N'.[VISITAS] WHERE USUARIO = @USUARIO) 

	SET @SQL   = ''SELECT @ID_VISITA = ID_VISITA  FROM '' + QUOTENAME(@CIA) + N''.[VISITAS] WHERE ID_VISITA =  @LAST''
	SET @PARAM = ''@ID_VISITA INT OUTPUT, @LAST INT''
	
	EXEC sys.sp_executesql @SQL,@PARAM,@ID_VISITA OUTPUT, @LAST 
';
    EXEC sys.sp_executesql @SQL_CIA_BATCH,
        N'@CLIENTE VARCHAR(20), @TIPO_VISITA VARCHAR(4), @FECHA_VISITA DATETIME, @LATITUD VARCHAR(50), @LONGITUD VARCHAR(50), @ESTADO_VISITA VARCHAR(4), @COMENTARIO VARCHAR(800), @DOCUMENTO VARCHAR(50), @VENDEDOR VARCHAR(4), @USUARIO VARCHAR(50), @DOC_VENC_DESCRIPCION VARCHAR(800), @DIRECCION VARCHAR(MAX), @CIA VARCHAR(20), @ID_VISITA VARCHAR(20) OUT',
        @CLIENTE = @CLIENTE,
        @TIPO_VISITA = @TIPO_VISITA,
        @FECHA_VISITA = @FECHA_VISITA,
        @LATITUD = @LATITUD,
        @LONGITUD = @LONGITUD,
        @ESTADO_VISITA = @ESTADO_VISITA,
        @COMENTARIO = @COMENTARIO,
        @DOCUMENTO = @DOCUMENTO,
        @VENDEDOR = @VENDEDOR,
        @USUARIO = @USUARIO,
        @DOC_VENC_DESCRIPCION = @DOC_VENC_DESCRIPCION,
        @DIRECCION = @DIRECCION,
        @CIA = @CIA,
        @ID_VISITA = @ID_VISITA OUTPUT;
END
GO
